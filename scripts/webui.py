# Embeds web/index.html (gzip, deterministic) into src/web/WebAssets.h so the
# firmware serves the administration page from flash without a filesystem.
import gzip
import hashlib
import os

Import("env")

ROOT = env["PROJECT_DIR"]
SRC = os.path.join(ROOT, "web", "index.html")
DST = os.path.join(ROOT, "src", "web", "WebAssets.h")


def build():
    with open(SRC, "rb") as f:
        raw = f.read()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    etag = hashlib.sha1(gz).hexdigest()[:16]
    lines = []
    lines.append("// Generated by scripts/webui.py from web/index.html. Do not edit.")
    lines.append("#pragma once")
    lines.append("#include <cstddef>")
    lines.append("#include <cstdint>")
    lines.append("namespace edk {")
    lines.append("static const size_t kIndexHtmlRawSize = %d;" % len(raw))
    lines.append('static const char kIndexHtmlEtag[] = "%s";' % etag)
    lines.append("static const size_t kIndexHtmlGzSize = %d;" % len(gz))
    lines.append("static const uint8_t kIndexHtmlGz[] = {")
    for i in range(0, len(gz), 16):
        lines.append("    " + ",".join("0x%02x" % b for b in gz[i:i + 16]) + ",")
    lines.append("};")
    lines.append("} // namespace edk")
    lines.append("")
    content = "\n".join(lines)
    old = None
    if os.path.exists(DST):
        with open(DST, "r") as f:
            old = f.read()
    if old != content:
        with open(DST, "w") as f:
            f.write(content)
    print("Web UI: %d bytes -> %d bytes gzip (%s)" % (len(raw), len(gz), "updated" if old != content else "unchanged"))


build()
